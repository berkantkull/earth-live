/**
 * Arayüz dili (Türkçe / İngilizce).
 *
 * Dil sırası: kullanıcının seçimi (localStorage) → tarayıcı dili (tr* ise Türkçe) → İngilizce.
 * Dil değişince sayfa yeniden yüklenir; böylece her metin ve biçim tutarlı yeniden oluşur.
 * Anahtar kümesi Türkçe sözlükten türetilir: İngilizce sözlükte eksik anahtar derlemeyi durdurur.
 */

export type Lang = 'tr' | 'en';

const STORAGE_KEY = 'earthlive.lang';

function detect(): Lang {
  if (typeof window === 'undefined') return 'tr';
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    // gizli pencere vb.
  }
  return (navigator.language || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export const lang: Lang = detect();
/** Intl biçimlendiricileri için yerel ayar (İngilizcede gün-ay sırası ve 24 saat için en-GB) */
export const locale = lang === 'tr' ? 'tr-TR' : 'en-GB';

export function setLang(next: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // kaydedilemese de bu yükleme için geçerli olur
  }
  location.reload();
}

