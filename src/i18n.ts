export const dictionaries: Record<Lang, Record<Key, string>> = { tr, en };

/** Çeviri; {ad} biçimindeki yer tutucular vars ile doldurulur */
export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[lang][key] ?? tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** HTML'deki data-i18n (metin) ve data-i18n-attr="öznitelik:anahtar;..." işaretlerini uygular */
export function applyStaticTranslations(root: ParentNode = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as Key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-attr]').forEach((el) => {
    for (const pair of (el.dataset.i18nAttr ?? '').split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim() as Key));
    }
  });
}
